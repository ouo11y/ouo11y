"""Builds project/kb/client-sdk-state/sdk-state-report.html from the JSON in
project/agents/sdk-state/findings/. Standard library only.

    python3 project/agents/sdk-state/scripts/build_report.py          # write the report
    python3 project/agents/sdk-state/scripts/build_report.py --check  # fail if it is stale

Inputs: requirements.json, audit-{web,ios,android,rn}.json, gaps.json (from build_gaps.py) and
overhead.json (from summarize_overhead.py). Also writes the budget table of
overhead.md between its budgets:begin and budgets:end markers."""
import html, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
DATA = ROOT / 'project/agents/sdk-state/findings'
OUT = ROOT / 'project/kb/client-sdk-state/sdk-state-report.html'
MD = ROOT / 'project/kb/client-sdk-state/overhead.md'
BEGIN, END = '<!-- budgets:begin, generated by build_report.py from findings/budgets.json -->', '<!-- budgets:end -->'
PLATFORMS = [('web', 'Web'), ('ios', 'iOS'), ('android', 'Android'), ('rn', 'React Native')]
STATUS = ['met', 'partial', 'not_met', 'na']
STATUS_LABEL = {'met': 'Met', 'partial': 'Partly met', 'not_met': 'Not met', 'na': 'Not applicable'}


def load(name):
    return json.loads((DATA / name).read_text())


def esc(s):
    return html.escape(str(s), quote=True)


def bar_chart(title, unit, rows, note='', fmt='{:.1f}'):
    """Horizontal bars, one row per variant. rows: [{label, sdk, value, lo, hi}]. One axis, from 0."""
    rows = [r for r in rows if r.get('value') is not None]
    if not rows:
        return ''
    vmax = max(max(r['value'], r.get('hi') or 0) for r in rows) or 1
    w, lw, rh, gap = 640, 190, 22, 8
    plot = w - lw - 80
    h = len(rows) * (rh + gap) + 28
    out = [f'<figure class="chart"><figcaption><strong>{esc(title)}</strong> <span class="unit">({esc(unit)})</span></figcaption>',
           f'<svg viewBox="0 0 {w} {h}" role="img" aria-label="{esc(title)}">']
    for t in range(0, 5):
        x = lw + plot * t / 4
        out.append(f'<line x1="{x:.1f}" x2="{x:.1f}" y1="0" y2="{h - 20}" class="grid"/>')
        out.append(f'<text x="{x:.1f}" y="{h - 6}" class="tick" text-anchor="middle">{esc(fmt.format(vmax * t / 4))}</text>')
    for i, r in enumerate(rows):
        y = i * (rh + gap)
        bw = max(plot * r['value'] / vmax, 1)
        cls = {'ouo': 's1', 'sentry': 's2'}.get(r['sdk'], 's0')
        tip = f"{r['label']}: {fmt.format(r['value'])} {unit}"
        if r.get('lo') is not None:
            tip += f" (range {fmt.format(r['lo'])} to {fmt.format(r['hi'])})"
        out.append(f'<g><title>{esc(tip)}</title>')
        out.append(f'<text x="{lw - 8}" y="{y + rh * 0.68:.1f}" class="lab" text-anchor="end">{esc(r["label"])}</text>')
        out.append(f'<path d="M{lw},{y} h{bw - 4:.1f} a4,4 0 0 1 4,4 v{rh - 8} a4,4 0 0 1 -4,4 h{-(bw - 4):.1f} z" class="{cls}"/>' if bw > 5 else
                   f'<rect x="{lw}" y="{y}" width="{bw:.1f}" height="{rh}" class="{cls}"/>')
        if r.get('lo') is not None and r.get('hi') is not None:
            x1, x2 = lw + plot * r['lo'] / vmax, lw + plot * r['hi'] / vmax
            out.append(f'<line x1="{x1:.1f}" x2="{x2:.1f}" y1="{y + rh / 2}" y2="{y + rh / 2}" class="whisk"/>')
        right = lw + plot * max(r['value'], r.get('hi') or 0) / vmax
        out.append(f'<text x="{max(lw + bw, right) + 6:.1f}" y="{y + rh * 0.68:.1f}" class="val">{esc(fmt.format(r["value"]))}</text></g>')
    out.append('</svg>')
    if note:
        out.append(f'<p class="note">{esc(note)}</p>')
    out.append('</figure>')
    return '\n'.join(out)


def stacked(counts_by_platform, total_key='applicable'):
    """One 100% bar per platform for the MUST rows that apply: met, partly met, not met."""
    w, lw, rh, gap = 480, 100, 26, 10
    plot = w - lw - 20
    h = len(counts_by_platform) * (rh + gap)
    out = [f'<svg viewBox="0 0 {w} {h}" role="img" aria-label="MUST compliance per platform">']
    for i, (p, label, c) in enumerate(counts_by_platform):
        y = i * (rh + gap)
        n = c['met'] + c['partial'] + c['not_met']
        out.append(f'<text x="{lw - 8}" y="{y + rh * 0.68}" class="lab" text-anchor="end">{esc(label)}</text>')
        x = lw
        for k, cls in (('met', 'good'), ('partial', 'warn'), ('not_met', 'crit')):
            bw = plot * c[k] / n
            if bw <= 0:
                continue
            out.append(f'<g><title>{esc(label)}: {STATUS_LABEL[k]} {c[k]} of {n}</title>'
                       f'<rect x="{x + 1:.1f}" y="{y}" width="{max(bw - 2, 1):.1f}" height="{rh}" rx="3" class="{cls}"/>'
                       + (f'<text x="{x + bw / 2:.1f}" y="{y + rh * 0.68}" class="inbar{" dark" if cls == "warn" else ""}" text-anchor="middle">{c[k]}</text>' if bw > 28 else '')
                       + '</g>')
            x += bw
    out.append('</svg>')
    return '\n'.join(out)


def budgets_md(budgets):
    """The budget table of overhead.md, so the Markdown and the report come from one file."""
    cell = lambda x: str(x).replace('|', '\\|')
    lines = ['| Budget | Web | iOS | Android | React Native | Basis | Enforced by |', '|---|---|---|---|---|---|---|']
    lines += ['| ' + ' | '.join(cell(b.get(k, '')) for k in ('budget', 'web', 'ios', 'android', 'rn', 'basis', 'method')) + ' |' for b in budgets]
    return '\n'.join(lines)


def with_budgets(md, budgets):
    i, j = md.index(BEGIN) + len(BEGIN), md.index(END)
    return md[:i] + '\n' + budgets_md(budgets) + '\n' + md[j:]


def main():
    reqs = load('requirements.json')
    audits = {p: load(f'audit-{p}.json') for p, _ in PLATFORMS}
    gaps = load('gaps.json')
    over = load('overhead.json')
    by_id = {p: {r['id']: r for r in audits[p]['requirements']} for p, _ in PLATFORMS}
    for p, _ in PLATFORMS:
        missing = {q['id'] for q in reqs} - set(by_id[p])
        if missing:
            sys.exit(f'audit-{p}.json misses {sorted(missing)}')

    # Headline counts: MUST rows applicable to each platform.
    counts = []
    for p, label in PLATFORMS:
        c = {k: 0 for k in STATUS}
        for q in reqs:
            if q['level'] == 'MUST':
                c[by_id[p][q['id']]['status']] += 1
        counts.append((p, label, c))

    # Compliance rows for the client-side table.
    comp = []
    for q in reqs:
        comp.append({'id': q['id'], 'level': q['level'], 'section': q['section'],
                     'text': re.sub(r'^[-|]\s*\*\*[A-Z]{3}-\d+\*\*\s*\|?\s*', '', q['text']).replace('**', '')[:400],
                     'p': {p: {k: by_id[p][q['id']][k] for k in ('status', 'evidence', 'method', 'note')} for p, _ in PLATFORMS}})
    viol = {p: audits[p]['violations'] for p, _ in PLATFORMS}
    arch = {p: audits[p]['architecture_notes'] for p, _ in PLATFORMS}
    meta = {p: {'version': audits[p].get('sdk_version', ''), 'how': audits[p].get('how_checked', '')} for p, _ in PLATFORMS}

    charts = []
    for group in over['charts']:
        charts.append(f'<h3>{esc(group["title"])}</h3><p>{esc(group.get("intro", ""))}</p><div class="charts">' +
                      ''.join(bar_chart(c['title'], c['unit'], c['rows'], c.get('note', ''), c.get('fmt', '{:.1f}')) for c in group['charts']) + '</div>')

    budgets = ''.join(
        f'<tr><td>{esc(b["budget"])}</td>' + ''.join(f'<td>{esc(b.get(p, ""))}</td>' for p, _ in PLATFORMS) +
        f'<td>{esc(b["basis"])}</td><td>{esc(b["method"])}</td></tr>' for b in over['budgets'])
    notm = ''.join(f'<li><strong>{esc(n["what"])}</strong>: {esc(n["why"])}</li>' for n in over['not_measured'])

    payload = json.dumps({'comp': comp, 'gaps': gaps, 'viol': viol, 'arch': arch, 'meta': meta}, separators=(',', ':')).replace('</', '<\\/')
    tpl = (ROOT / 'project/agents/sdk-state/scripts/report_template.html.in').read_text()
    page = (tpl.replace('@@STACKED@@', stacked(counts))
            .replace('@@HEADLINE@@', ''.join(
                f'<div class="tile"><div class="big">{c["met"]}<span class="of"> / {c["met"] + c["partial"] + c["not_met"]}</span></div>'
                f'<div>{esc(label)}: MUSTs met</div><div class="muted">{c["partial"]} partly, {c["not_met"]} not met, {c["na"]} not applicable</div></div>'
                for p, label, c in counts))
            .replace('@@CHARTS@@', '\n'.join(charts))
            .replace('@@BUDGETS@@', budgets)
            .replace('@@NOTMEASURED@@', notm)
            .replace('@@OVERHEAD_SETUP@@', esc(over['setup']))
            .replace('@@DATA@@', payload))
    md = MD.read_text()
    md_new = with_budgets(md, over['budgets'])
    if '--check' in sys.argv:
        stale = [f.relative_to(ROOT) for f, now, want in ((OUT, OUT.read_text() if OUT.exists() else '', page), (MD, md, md_new)) if now != want]
        if stale:
            sys.exit(f'stale: {", ".join(map(str, stale))}: run build_report.py')
        print('report and overhead.md budget table up to date')
        return
    OUT.write_text(page)
    MD.write_text(md_new)
    print('wrote', OUT.relative_to(ROOT), len(page) // 1024, 'KiB, and the budget table in', MD.relative_to(ROOT))


if __name__ == '__main__':
    main()
