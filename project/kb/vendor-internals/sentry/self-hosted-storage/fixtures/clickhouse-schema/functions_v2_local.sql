CREATE MATERIALIZED VIEW default.functions_v2_local TO default.functions_mv_local
(
    `project_id` UInt64,
    `transaction_name` String,
    `timestamp` DateTime,
    `depth` UInt32,
    `parent_fingerprint` UInt64,
    `fingerprint` UInt64,
    `name` String,
    `package` String,
    `path` String,
    `is_application` UInt8,
    `platform` LowCardinality(String),
    `environment` LowCardinality(Nullable(String)),
    `release` LowCardinality(Nullable(String)),
    `os_name` LowCardinality(String),
    `os_version` LowCardinality(String),
    `retention_days` UInt16,
    `count` AggregateFunction(count, Float64),
    `percentiles` AggregateFunction(quantiles(0.5, 0.75, 0.9, 0.95, 0.99), Float64),
    `min` AggregateFunction(min, Float64),
    `max` AggregateFunction(max, Float64),
    `avg` AggregateFunction(avg, Float64),
    `sum` AggregateFunction(sum, Float64),
    `worst` AggregateFunction(argMax, UUID, Float64),
    `examples` AggregateFunction(groupUniqArray(5), UUID),
    `worst_v2` AggregateFunction(argMax, Tuple(
        UUID,
        String,
        Nullable(DateTime64(6)),
        Nullable(DateTime64(6))), Float64),
    `examples_v2` AggregateFunction(groupUniqArray(5), Tuple(
        UUID,
        String,
        Nullable(DateTime64(6)),
        Nullable(DateTime64(6)))),
    `profiling_type` LowCardinality(String) DEFAULT 'transaction'
)
AS SELECT
    project_id,
    transaction_name,
    name,
    package,
    path,
    fingerprint,
    parent_fingerprint,
    depth,
    is_application,
    profiling_type,
    platform,
    environment,
    release,
    os_name,
    os_version,
    toDateTime(3600 * intDiv(toUnixTimestamp(timestamp), 3600)) AS timestamp,
    retention_days,
    countState(arrayJoin(durations) AS duration) AS count,
    quantilesState(0.5, 0.75, 0.9, 0.95, 0.99)(duration) AS percentiles,
    minState(duration) AS min,
    maxState(duration) AS max,
    avgState(duration) AS avg,
    sumState(duration) AS sum,
    argMaxState(profile_id, duration) AS worst,
    argMaxState((profile_id, thread_id, start_timestamp, end_timestamp), duration) AS worst_v2,
    groupUniqArrayState(5)(profile_id) AS examples,
    groupUniqArrayState(5)((profile_id, thread_id, start_timestamp, end_timestamp)) AS examples_v2
FROM default.functions_raw_local
WHERE materialization_version = 1
GROUP BY
    project_id,
    transaction_name,
    name,
    package,
    path,
    fingerprint,
    parent_fingerprint,
    depth,
    is_application,
    profiling_type,
    platform,
    environment,
    release,
    os_name,
    os_version,
    timestamp,
    retention_days
