CREATE MATERIALIZED VIEW default.replays_aggregation_mv TO default.replays_aggregated_local
(
    `project_id` UInt64,
    `to_hour_timestamp` DateTime,
    `replay_id` UUID,
    `retention_days` UInt16,
    `browser_name` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `browser_version` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `count_dead_clicks` AggregateFunction(sum, UInt64),
    `count_errors` AggregateFunction(sum, UInt64),
    `count_infos` AggregateFunction(sum, UInt64),
    `count_rage_clicks` AggregateFunction(sum, UInt64),
    `count_segments` AggregateFunction(count, Nullable(UInt64)),
    `count_urls` AggregateFunction(sum, UInt64),
    `count_warnings` AggregateFunction(sum, UInt64),
    `device_brand` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `device_family` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `device_model` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `device_name` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `dist` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `environment` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `finished_at` AggregateFunction(maxIf, DateTime, UInt8),
    `ip_address_v4` AggregateFunction(any, Nullable(IPv4)),
    `ip_address_v6` AggregateFunction(any, Nullable(IPv6)),
    `is_archived` AggregateFunction(sum, Nullable(UInt64)),
    `min_segment_id` AggregateFunction(min, Nullable(UInt16)),
    `os_name` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `os_version` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `platform` AggregateFunction(anyIf, String, UInt8),
    `sdk_name` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `sdk_version` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `started_at` AggregateFunction(min, Nullable(DateTime)),
    `user` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `user_id` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `user_name` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8)),
    `user_email` AggregateFunction(anyIf, Nullable(String), Nullable(UInt8))
)
AS SELECT
    project_id,
    toStartOfHour(timestamp) AS to_hour_timestamp,
    replay_id,
    retention_days,
    anyIfState(browser_name, browser_name != '') AS browser_name,
    anyIfState(browser_version, browser_version != '') AS browser_version,
    sumState(toUInt64(click_is_dead)) AS count_dead_clicks,
    sumState(toUInt64((error_id != '00000000-0000-0000-0000-000000000000') OR (fatal_id != '00000000-0000-0000-0000-000000000000'))) AS count_errors,
    sumState(toUInt64((debug_id != '00000000-0000-0000-0000-000000000000') OR (info_id != '00000000-0000-0000-0000-000000000000'))) AS count_infos,
    sumState(toUInt64(click_is_rage)) AS count_rage_clicks,
    countState(toUInt64(segment_id)) AS count_segments,
    sumState(length(urls)) AS count_urls,
    sumState(toUInt64(warning_id != '00000000-0000-0000-0000-000000000000')) AS count_warnings,
    anyIfState(device_brand, device_brand != '') AS device_brand,
    anyIfState(device_family, device_family != '') AS device_family,
    anyIfState(device_model, device_model != '') AS device_model,
    anyIfState(device_name, device_name != '') AS device_name,
    anyIfState(dist, dist != '') AS dist,
    maxIfState(timestamp, segment_id IS NOT NULL) AS finished_at,
    anyIfState(environment, environment != '') AS environment,
    anyState(ip_address_v4) AS ip_address_v4,
    anyState(ip_address_v6) AS ip_address_v6,
    sumState(toUInt64(is_archived)) AS is_archived,
    anyIfState(os_name, os_name != '') AS os_name,
    anyIfState(os_version, os_version != '') AS os_version,
    anyIfState(platform, platform != '') AS platform,
    anyIfState(sdk_name, sdk_name != '') AS sdk_name,
    anyIfState(sdk_version, sdk_version != '') AS sdk_version,
    minState(replay_start_timestamp) AS started_at,
    anyIfState(user, user != '') AS user,
    anyIfState(user_id, user_id != '') AS user_id,
    anyIfState(user_name, user_name != '') AS user_name,
    anyIfState(user_email, user_email != '') AS user_email,
    minState(segment_id) AS min_segment_id
FROM default.replays_local
GROUP BY
    project_id,
    toStartOfHour(timestamp),
    replay_id,
    retention_days
