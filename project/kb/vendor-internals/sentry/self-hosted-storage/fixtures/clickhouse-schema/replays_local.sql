CREATE TABLE default.replays_local
(
    `replay_id` UUID,
    `debug_id` UUID,
    `count_info_events` UInt8 MATERIALIZED (debug_id != '00000000-0000-0000-0000-000000000000') + (info_id != '00000000-0000-0000-0000-000000000000'),
    `count_warning_events` UInt8 MATERIALIZED warning_id != '00000000-0000-0000-0000-000000000000',
    `count_error_events` UInt8 MATERIALIZED (error_id != '00000000-0000-0000-0000-000000000000') + (fatal_id != '00000000-0000-0000-0000-000000000000'),
    `info_id` UUID,
    `warning_id` UUID,
    `error_id` UUID,
    `fatal_id` UUID,
    `replay_type` LowCardinality(Nullable(String)),
    `error_sample_rate` Nullable(Float64),
    `session_sample_rate` Nullable(Float64),
    `event_hash` UUID,
    `segment_id` Nullable(UInt16),
    `trace_ids` Array(UUID),
    `_trace_ids_hashed` Array(UInt64) MATERIALIZED arrayMap(t -> cityHash64(t), trace_ids),
    `title` Nullable(String),
    `url` Nullable(String),
    `urls` Array(String),
    `segment_names` Array(String),
    `is_archived` Nullable(UInt8),
    `error_ids` Array(UUID),
    `_error_ids_hashed` Array(UInt64) MATERIALIZED arrayMap(t -> cityHash64(t), error_ids),
    `project_id` UInt64,
    `timestamp` DateTime,
    `replay_start_timestamp` Nullable(DateTime),
    `platform` LowCardinality(String),
    `environment` LowCardinality(Nullable(String)),
    `release` Nullable(String),
    `dist` Nullable(String),
    `ip_address_v4` Nullable(IPv4),
    `ip_address_v6` Nullable(IPv6),
    `user` Nullable(String),
    `user_id` Nullable(String),
    `user_name` Nullable(String),
    `user_email` Nullable(String),
    `user_geo_city` String,
    `user_geo_country_code` String,
    `user_geo_region` String,
    `user_geo_subdivision` String,
    `viewed_by_id` UInt64,
    `os_name` LowCardinality(Nullable(String)),
    `os_version` Nullable(String),
    `browser_name` LowCardinality(Nullable(String)),
    `browser_version` Nullable(String),
    `device_name` LowCardinality(Nullable(String)),
    `device_brand` LowCardinality(Nullable(String)),
    `device_family` LowCardinality(Nullable(String)),
    `device_model` LowCardinality(Nullable(String)),
    `ota_updates_channel` String,
    `ota_updates_runtime_version` String,
    `ota_updates_update_id` String,
    `sdk_name` LowCardinality(Nullable(String)),
    `sdk_version` LowCardinality(Nullable(String)),
    `tags.key` Array(String),
    `tags.value` Array(String),
    `_tags_hash_map` Array(UInt64) MATERIALIZED arrayMap((k, v) -> cityHash64(concat(replaceRegexpAll(k, '(\\=|\\\\)', '\\\\\\1'), '=', v)), tags.key, tags.value),
    `click_node_id` UInt32 DEFAULT 0,
    `click_tag` LowCardinality(String) DEFAULT '',
    `click_id` String DEFAULT '',
    `click_class` Array(String),
    `click_text` String DEFAULT '',
    `click_role` LowCardinality(String) DEFAULT '',
    `click_alt` String DEFAULT '',
    `click_testid` String DEFAULT '',
    `click_aria_label` String DEFAULT '',
    `click_title` String DEFAULT '',
    `click_component_name` String,
    `click_is_dead` UInt8,
    `click_is_rage` UInt8,
    `tap_message` String,
    `tap_view_class` String,
    `tap_view_id` String,
    `count_errors` UInt16 MATERIALIZED length(error_ids),
    `count_urls` UInt16 MATERIALIZED length(urls),
    `retention_days` UInt16,
    `partition` UInt16,
    `offset` UInt64,
    INDEX bf_trace_ids_hashed _trace_ids_hashed TYPE bloom_filter() GRANULARITY 1,
    INDEX bf_error_ids_hashed _error_ids_hashed TYPE bloom_filter() GRANULARITY 1,
    INDEX bf_user_id user_id TYPE bloom_filter() GRANULARITY 1,
    INDEX bf_user_email user_email TYPE bloom_filter() GRANULARITY 1,
    INDEX bf_ip_address_v4 ip_address_v4 TYPE bloom_filter() GRANULARITY 1,
    INDEX bf_tags_hash_map _tags_hash_map TYPE bloom_filter GRANULARITY 1
)
ENGINE = ReplacingMergeTree
PARTITION BY (retention_days, toMonday(timestamp))
ORDER BY (project_id, toStartOfDay(timestamp), cityHash64(replay_id), event_hash)
TTL timestamp + toIntervalDay(retention_days)
SETTINGS index_granularity = 8192
